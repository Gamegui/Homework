def bg(slide, color):
    fill = slide.background.fill
    fill.solid()
    fill.fore_color.rgb = color

def box(slide, l, t, w, h, fill_color=None):
    from pptx.enum.shapes import MSO_SHAPE
    s = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(l), Inches(t), Inches(w), Inches(h))
    s.line.fill.background()
    if fill_color:
        s.fill.solid()
        s.fill.fore_color.rgb = fill_color
    return s

def text_in(shape, text, size=20, bold=False, color=DARK, align=PP_ALIGN.LEFT):
    shape.text_frame.clear()
    shape.text_frame.word_wrap = True
    p = shape.text_frame.paragraphs[0]
    p.text = text
    p.font.size = Pt(size)
    p.font.bold = bold
    p.font.color.rgb = color
    p.alignment = align
    return shape.text_frame

def bullets(shape, items, size=17, color=DARK, space=Pt(6)):
    tf = shape.text_frame
    tf.clear()
    tf.word_wrap = True
    for i, (head, body) in enumerate(items):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.space_after = space
        p.level = 0
        if head:
            r = p.add_run()
            r.text = head
            r.font.size = Pt(size)
            r.font.bold = True
            r.font.color.rgb = NAVY
        if body:
            r = p.add_run()
            r.text = body
            r.font.size = Pt(size)
            r.font.color.rgb = color
    return tf

def footer(slide, n, total):
    t = slide.shapes.add_textbox(Inches(0.6), Inches(6.95), Inches(11), Inches(0.35))
    text_in(t, "Основы российской государственности  •  Ключевые военные победы России",
            size=11, color=GRAY)
    t2 = slide.shapes.add_textbox(Inches(12.1), Inches(6.95), Inches(0.7), Inches(0.35))
    text_in(t2, f"{n}/{total}", size=11, color=GRAY, align=PP_ALIGN.RIGHT)

def header(slide, title, kicker=None):
    box(slide, 0, 0, 13.33, 1.55, NAVY)
    box(slide, 0, 1.55, 13.33, 0.07, GOLD)
    t = slide.shapes.add_textbox(Inches(0.7), Inches(0.25), Inches(11.9), Inches(1.1))
    tf = t.text_frame
    tf.word_wrap = True
    if kicker:
        p = tf.paragraphs[0]
        p.text = kicker
        p.font.size = Pt(14)
        p.font.color.rgb = GOLD
        p.font.bold = True
        p2 = tf.add_paragraph()
        p2.text = title
        p2.font.size = Pt(30)
        p2.font.bold = True
        p2.font.color.rgb = WHITE
    else:
        p = tf.paragraphs[0]
        p.text = title
        p.font.size = Pt(30)
        p.font.bold = True
        p.font.color.rgb = WHITE

def itog_box(slide, text):
    c = box(slide, 0.7, 5.15, 11.9, 1.45, LIGHT)
    tf = c.text_frame
    tf.clear()
    tf.word_wrap = True
    tf.vertical_anchor = MSO_ANCHOR.MIDDLE
    tf.margin_left = Inches(0.25)
    tf.margin_right = Inches(0.25)
    p = tf.paragraphs[0]
    r = p.add_run()
    r.text = "Итог: "
    r.font.size = Pt(17)
    r.font.bold = True
    r.font.color.rgb = NAVY
    r = p.add_run()
    r.text = text
    r.font.size = Pt(17)
    r.font.color.rgb = DARK
    box(slide, 0.7, 5.15, 0.09, 1.45, GOLD)

def note(slide, text):
    slide.notes_slide.placeholders[1].text = text

